# makes the pulled sounds crisp: python art/sfx/build.py
# reads sounds.txt, cuts each source to its transient, cleans it up, and packs every take into one atlas like the art:
# art/sfx/sfx.ogg + sfx.json ({name: [[start_s, length_s], ...]}) + CREDITS.md
# needs ffmpeg and numpy. see docs/SOUND.md §2
import glob
import json
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, 'raw')
RATE = 44100
MIN_TAKES = 3  # round-robin needs something to rotate
GAP = int(RATE * 0.05)  # silence between takes in the atlas


def decode(path, highpass):
    # mono float at 44.1k, highpassed, a small presence lift
    chain = f'highpass=f={highpass},equalizer=f=5000:t=q:w=1:g=2' if highpass else 'equalizer=f=5000:t=q:w=1:g=2'
    raw = subprocess.run(
        ['ffmpeg', '-v', 'error', '-i', path, '-af', chain, '-ac', '1', '-ar', str(RATE), '-f', 'f32le', '-'],
        check=True, capture_output=True).stdout
    audio = np.frombuffer(raw, dtype=np.float32).copy()
    if audio.size == 0 or not np.any(audio):
        raise SystemExit(f'{path}: silent or empty')
    return audio


def crisp(audio, max_ms):
    # start 2 ms before the transient, end where it has decayed 40 dB or at max_ms, fade the last 8 ms
    peak = np.max(np.abs(audio))
    loud = np.nonzero(np.abs(audio) > peak * 0.05)[0]
    start = max(0, loud[0] - int(RATE * 0.002))
    env = np.abs(audio[start:])
    alive = np.nonzero(env > peak * 0.01)[0]
    end = min(alive[-1] + 1, int(RATE * max_ms / 1000))
    clip = audio[start:start + end].copy()
    fade = min(len(clip), int(RATE * 0.008))
    clip[-fade:] *= np.linspace(1, 0, fade)
    return clip * (10 ** (-1 / 20) / np.max(np.abs(clip)))  # peak at -1 dBFS


def repitch(audio, rate):
    # resample so it plays `rate` times faster (and higher)
    n = int(len(audio) / rate)
    return np.interp(np.arange(n) * rate, np.arange(len(audio)), audio).astype(np.float32)


def encode(audio, path):
    subprocess.run(
        ['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(RATE), '-ac', '1', '-i', '-',
         '-c:a', 'libvorbis', '-q:a', '6', path],
        input=audio.astype(np.float32).tobytes(), check=True)


def parse():
    packs, sounds = {}, []
    for line in open(os.path.join(HERE, 'sounds.txt')):
        line = line.split('#')[0].strip()
        if not line:
            continue
        words = line.split()
        if words[0] == 'pack':  # pack <dir> <license> <author> <url>
            packs[words[1]] = (words[2], words[3], ' '.join(words[4:]))
            continue
        name, max_ms, highpass, *globs = words
        files = sorted(f for g in globs for f in glob.glob(os.path.join(RAW, g)))
        if not files:
            raise SystemExit(f'{name}: no files match {globs}')
        sounds.append((name, int(max_ms), int(highpass), files))
    return packs, sounds


def main():
    packs, sounds = parse()
    credits, atlas, index, at = [], [], {}, GAP
    for name, max_ms, highpass, files in sounds:
        takes = [crisp(decode(f, highpass), max_ms) for f in files]
        # one or two sources: add copies a little up and down so the rotation still varies
        pitches = [1.03, 0.97, 1.05, 0.95]
        while len(takes) < MIN_TAKES:
            takes.append(repitch(takes[len(takes) % len(files)], pitches[len(takes) - len(files)]))
        index[name] = []
        for take in takes:
            index[name].append([round(at / RATE, 5), round(len(take) / RATE, 5)])
            atlas += [np.zeros(GAP, np.float32) if not atlas else np.zeros(0, np.float32), take, np.zeros(GAP, np.float32)]
            at += len(take) + GAP
        used = sorted({os.path.relpath(f, RAW).split(os.sep)[0] for f in files})
        for pack in used:
            if pack not in packs:
                raise SystemExit(f'{name}: pack {pack} has no credit line in sounds.txt')
        credits.append(f'| `{name}` | {len(takes)} | ' + ', '.join(os.path.relpath(f, RAW) for f in files) + ' |')
        print(f'{name}: {len(takes)} takes, {max(len(t) for t in takes) * 1000 // RATE} ms')
    audio = np.concatenate(atlas)
    if len(audio) != at:
        raise SystemExit(f'atlas is {len(audio)} samples, index says {at}')
    encode(audio, os.path.join(HERE, 'sfx.ogg'))
    with open(os.path.join(HERE, 'sfx.json'), 'w') as f:
        json.dump(index, f, separators=(',', ':'))
    print(f'sfx.ogg: {len(audio) / RATE:.1f} s, {len(index)} sounds')
    with open(os.path.join(HERE, 'CREDITS.md'), 'w') as f:
        f.write('# Sound credits\n\nGenerated by `art/sfx/build.py` from `sounds.txt`. Every source is CC0: no credit needed, given anyway.\n\n')
        f.write('| Pack | License | Author | Source |\n|---|---|---|---|\n')
        for pack, (lic, author, url) in sorted(packs.items()):
            f.write(f'| `{pack}` | {lic} | {author} | {url} |\n')
        f.write('\n| Sound | Takes | From |\n|---|---|---|\n' + '\n'.join(credits) + '\n')


if __name__ == '__main__':
    sys.exit(main())
